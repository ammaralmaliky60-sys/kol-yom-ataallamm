import {readFile,writeFile} from 'node:fs/promises';
const root=new URL('../dist/',import.meta.url);
const sources=[['base','styles.css'],['glass','glass.css'],['vivid','vivid.css'],['theme','theme.css']];
let css='/* Generated by scripts/bundle-styles.mjs. Edit the named source layers. */\n@layer base,glass,vivid,theme;\n';
for(const [layer,file] of sources){
 const source=(await readFile(new URL(file,root),'utf8')).replace(/^@import[^;]+;\s*/,'');
 css+=`\n@layer ${layer} {\n${source}\n}\n`;
}
await writeFile(new URL('site.css',root),css);
console.log(`Styles bundled: ${Buffer.byteLength(css)} bytes`);
